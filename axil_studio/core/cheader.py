"""C header of the whole address map: what software needs to reach every register.

A register map alone has no address (an IP can be placed several times, anywhere), so the C header
is made from the address map, where every IP instance has its base:

    /* register maps: one block per IP definition, offsets from the IP's base */
    #define AXILUART_PHY_SETUP_OFFSET            0x00u
    #define AXILUART_PHY_SETUP_DATA_BITS_SHIFT   28u
    #define AXILUART_PHY_SETUP_DATA_BITS_MASK    0x30000000u
    /* address map: one block per instance */
    #define UART0_BASE   0x60001000u
    #define UART0_SIZE   0x00001000u
    #define UART0_SETUP  (UART0_BASE + AXILUART_PHY_SETUP_OFFSET)

External slaves and subsystems get their base and window size. Command line:
    python -m axil_studio.core.cheader project.axproj.json -o soc_map.h
"""

import re

from . import addrmap as A
from .model import single_line

GENERATOR = "AXIL Studio"


def c_name(text):
    """A C identifier (upper case) from a name."""
    s = re.sub(r"[^0-9A-Za-z_]", "_", str(text)).upper()
    return s if s and not s[0].isdigit() else "_" + s


def _comment(text):
    return single_line(text).replace("*/", "* /")


def _c_str(text):
    return single_line(text).replace("\\", "\\\\").replace('"', '\\"')


def header_name(project):
    return f"{c_name(project.name).lower()}_map.h"


def gen_system_header(project):
    """The C header of the project's address map (register maps + every instance)."""
    from .axilgen import spec_from_ipblock
    guard = c_name(header_name(project).replace(".", "_"))
    L = [f"/* {_comment(project.name)}: address map and register maps (generated by {GENERATOR}) */",
         f"#ifndef {guard}", f"#define {guard}", ""]
    used = []
    for inst in project.leaf_instances():
        if inst.ip and inst.ip not in used and project.get_ip(inst.ip) is not None:
            used.append(inst.ip)
    if used:
        L += ["/* ==== Register maps: offsets from the IP's base address ==== */", ""]
    specs = {}
    defined = {guard}
    for name in used:
        ip = project.get_ip(name)
        spec = spec_from_ipblock(ip)
        specs[name] = spec
        m = c_name(ip.name)
        L.append(f"/* {_comment(ip.name)} {_comment(spec.version)}: {_comment(ip.desc)} */".replace(":  */", " */"))
        L.append(f'#define {m}_IP_VERSION  "{_c_str(spec.version)}"')
        defined.add(f"{m}_IP_VERSION")
        for r in sorted(spec.regs, key=lambda r: r.offset):
            rn = f"{m}_{c_name(r.name)}"
            L.append(f"#define {rn}_OFFSET  0x{r.offset:02X}u   /* {r.access} {_comment(r.desc)} */")
            defined.add(f"{rn}_OFFSET")
            for f in sorted(r.fields, key=lambda f: f.lsb):
                fn = rn if f.name.upper() == r.name.upper() else f"{rn}_{c_name(f.name)}"
                L.append(f"#define {fn}_SHIFT  {f.lsb}u")
                L.append(f"#define {fn}_MASK   0x{f.mask:08X}u   /* {f.kind} */")
                defined.update((f"{fn}_SHIFT", f"{fn}_MASK"))
        L.append("")
    L += ["/* ==== Address map: base address and window of every instance ==== */", ""]
    for inst, parent in project.walk():
        n = c_name(inst.name)
        size = A.window_of(project, inst)
        where = f"in {parent.name}" if parent is not None else "top bus"
        if inst.bridge:
            kind = "subsystem"
        elif inst.external:
            kind = "external slave"
        else:
            kind = inst.ip
        L.append(f"/* {_comment(inst.name)}: {_comment(kind)}, {_comment(where)} */")
        L.append(f"#define {n}_BASE  0x{inst.base & 0xFFFFFFFF:08X}u")
        size_lit = f"0x{size:08X}u" if size <= 0xFFFFFFFF else f"0x{size:X}ULL"
        L.append(f"#define {n}_SIZE  {size_lit}")
        defined.update((f"{n}_BASE", f"{n}_SIZE"))
        ip = project.get_ip(inst.ip) if inst.ip else None
        if ip is not None:
            m = c_name(ip.name)
            regs = specs[ip.name].regs if ip.name in specs else sorted(ip.registers, key=lambda r: r.offset)
            for r in regs:
                rc = c_name(r.name)
                macro = f"{n}_{rc}"
                if macro in defined:
                    macro = f"{n}_REG_{rc}"
                defined.add(macro)
                L.append(f"#define {macro}  ({n}_BASE + {m}_{rc}_OFFSET)   "
                         f"/* 0x{(inst.base + r.offset) & 0xFFFFFFFF:08X} */")
        L.append("")
    L.append(f"#endif /* {guard} */")
    return "\n".join(L) + "\n"


def main(argv=None):
    import argparse
    import os
    import sys
    from .model import Project
    ap = argparse.ArgumentParser(description="C header of an AXIL Studio project's address map")
    ap.add_argument("project", help=".axproj.json")
    ap.add_argument("-o", "--output", help="header file (default: <project>_map.h next to the project)")
    a = ap.parse_args(argv)
    try:
        proj = Project.load(a.project)
        out = a.output or os.path.join(os.path.dirname(os.path.abspath(a.project)), header_name(proj))
        with open(out, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(gen_system_header(proj))
    except (OSError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    print(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
